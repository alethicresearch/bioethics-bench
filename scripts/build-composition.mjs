#!/usr/bin/env node
/**
 * What the corpus is made of, counted once and published for everything that quotes it.
 *
 * The composition — how many policies are directly sourced, how the three types are distributed,
 * how each type label was arrived at — belongs in the paper, on the site and in the resource card,
 * and those three drifted apart the last time they were written by hand. This counts it from the
 * published files and writes both a machine-readable resource for the site and a markdown table
 * for the documents, so a number can only change by the data changing.
 *
 *   node scripts/build-composition.mjs           # verify the committed files are current
 *   node scripts/build-composition.mjs --write   # regenerate them
 */
import fs from 'node:fs';
import path from 'node:path';

const ROOT = process.cwd();
const CASES = JSON.parse(fs.readFileSync(path.join(ROOT, 'resources/cases/full-200-cases.v1.json'), 'utf8'));
const SOURCES = JSON.parse(fs.readFileSync(path.join(ROOT, 'resources/cases/case-sources.v1.json'), 'utf8'));
const JSON_OUT = path.join(ROOT, 'resources/cases/composition.v1.json');
const DOC_OUT = path.join(ROOT, 'docs/COMPOSITION.md');

const TYPES = ['public', 'expert', 'framework'];
const SOURCINGS = ['direct', 'inferred', 'constructed'];
const ROUTES = ['reviewed', 'case-record', 'wording', 'authored'];

const policies = CASES.cases.flatMap((c) => c.policies);
const tally = (items, key) => items.reduce((acc, item) => {
  const k = key(item);
  acc[k] = (acc[k] || 0) + 1;
  return acc;
}, {});
const zeroed = (keys) => Object.fromEntries(keys.map((k) => [k, 0]));

const sourcing = { ...zeroed(SOURCINGS), ...tally(policies, (p) => p.sourcing) };
const routes = { ...zeroed(ROUTES), ...tally(policies, (p) => p.type_route) };
const combinations = tally(policies, (p) => p.types.slice().sort().join('+'));

/* A policy may carry more than one type, so the type figures count assignments rather than
   policies and do not sum to the corpus. Said here so the page and the paper can say it too. */
const byType = {};
for (const type of TYPES) {
  const held = policies.filter((p) => p.types.includes(type));
  byType[type] = {
    assignments: held.length,
    sourcing: { ...zeroed(SOURCINGS), ...tally(held, (p) => p.sourcing) },
    written_by_bench: held.filter((p) => p.written_by_bench).length,
    per_case: (() => {
      const counts = CASES.cases.map((c) => c.policies.filter((p) => p.types.includes(type)).length);
      return {
        mean: Number((counts.reduce((a, b) => a + b, 0) / counts.length).toFixed(2)),
        min: Math.min(...counts),
        max: Math.max(...counts),
      };
    })(),
  };
}

const citations = Object.values(SOURCES.cases).flatMap((c) => c.sources);
const perCaseCitations = Object.values(SOURCES.cases).map((c) => c.sources.length);
const composition = {
  resource_id: 'bioethics-bench-composition',
  resource_version: '1.0.0',
  generated_from: {
    cases: CASES.resource_version || null,
    sources: SOURCES.resource_version || null,
  },
  cases: CASES.cases.length,
  policies: policies.length,
  written_by_bench: policies.filter((p) => p.written_by_bench).length,
  cases_objecting_to_pool: CASES.cases.filter((c) => c.case_file_objects_to_pool).length,
  sourcing,
  type_combinations: combinations,
  by_type: byType,
  type_routes: routes,
  citations: {
    total: citations.length,
    resolved: citations.filter((s) => s.resolved).length,
    cases_with_two_or_fewer: perCaseCitations.filter((n) => n <= 2).length,
    policy_level_cases: SOURCES.cases_with_policy_sources,
    layered_cases: SOURCES.cases_with_layered_sources,
    cases_with_layer_notes: SOURCES.cases_with_layer_notes,
  },
};

const n = (x) => Number(x).toLocaleString('en-US');
const pct = (part, whole) => `${((part / whole) * 100).toFixed(1)}%`;
const ROUTE_LABEL = {
  reviewed: 'Confirmed in an approved crosswalk',
  'case-record': 'Carried over from the case record',
  wording: 'Read from the policy wording',
  authored: 'Assigned when the policy was written',
};
const SOURCING_LABEL = { direct: 'Direct source', inferred: 'Inferred from source', constructed: 'Constructed' };
const TYPE_LABEL = { public: 'Public', expert: 'Expert', framework: 'Framework' };

const doc = `# What the collection is made of

Generated by \`node scripts/build-composition.mjs --write\` from the published files. Regenerate it
rather than editing it; these numbers are quoted on the site and in the paper.

${n(composition.cases)} cases carry ${n(composition.policies)} policies.

## How each policy was sourced

| Sourcing | Policies | Share |
|---|---:|---:|
${SOURCINGS.map((s) => `| ${SOURCING_LABEL[s]} | ${n(sourcing[s])} | ${pct(sourcing[s], composition.policies)} |`).join('\n')}

${composition.written_by_bench} of the ${sourcing.constructed} constructed policies were written by the Bench for cases recording no
policy of one type; the rest were constructed when the case was authored.

## Policy type

A policy may represent more than one kind of position, so these count assignments and do not sum
to ${n(composition.policies)}.

| Type | Assignments | Per case (mean) | Range |
|---|---:|---:|---:|
${TYPES.map((t) => `| ${TYPE_LABEL[t]} | ${n(byType[t].assignments)} | ${byType[t].per_case.mean} | ${byType[t].per_case.min}–${byType[t].per_case.max} |`).join('\n')}

| Combination | Policies |
|---|---:|
${Object.entries(combinations).sort((a, b) => b[1] - a[1]).map(([k, v]) => `| ${k.split('+').map((t) => TYPE_LABEL[t]).join(' + ')} | ${n(v)} |`).join('\n')}

## Type against sourcing

| Type | ${SOURCINGS.map((s) => SOURCING_LABEL[s]).join(' | ')} |
|---|---:|---:|---:|
${TYPES.map((t) => `| ${TYPE_LABEL[t]} | ${SOURCINGS.map((s) => n(byType[t].sourcing[s])).join(' | ')} |`).join('\n')}

${byType.expert.sourcing.direct} of the ${sourcing.direct} directly sourced policies are Expert. A guideline states a policy in
nearly the words a policy needs; a survey reports a preference and a framework supplies a
principle, and both take a step to become one. Public is the thinnest layer, ${byType.public.assignments} assignments
against ${byType.expert.assignments} Expert, and the most constructed.

## How each type label was arrived at

| Route | Policies | Share |
|---|---:|---:|
${ROUTES.map((r) => `| ${ROUTE_LABEL[r]} | ${n(routes[r])} | ${pct(routes[r], composition.policies)} |`).join('\n')}

Only the first has been checked, and that check is an editorial crosswalk to a released record,
not an independent re-derivation. The third is the smallest and the likeliest to be wrong, so
review starts there.

## Sources

${composition.citations.resolved} of the ${composition.citations.total} citations recorded across the cases resolve to a canonical locator; the
rest resolve to a scholarly search. ${composition.citations.cases_with_two_or_fewer} cases rest on two citations or fewer.
${composition.citations.policy_level_cases} cases record citations policy by policy, and ${composition.citations.cases_with_layer_notes} carry the case file's account of the
evidence behind each kind of position.
`;

const jsonText = `${JSON.stringify(composition, null, 2)}\n`;
if (process.argv.includes('--write')) {
  fs.writeFileSync(JSON_OUT, jsonText);
  fs.writeFileSync(DOC_OUT, doc);
  console.log(`Wrote ${path.relative(ROOT, JSON_OUT)} and ${path.relative(ROOT, DOC_OUT)}.`);
} else {
  for (const [file, expected] of [[JSON_OUT, jsonText], [DOC_OUT, doc]]) {
    if (!fs.existsSync(file)) throw new Error(`${path.relative(ROOT, file)} is missing; run with --write`);
    if (fs.readFileSync(file, 'utf8') !== expected) throw new Error(`${path.relative(ROOT, file)} is stale; run with --write`);
  }
  console.log(`Verified composition: ${composition.policies} policies, ${sourcing.direct} direct / ${sourcing.inferred} inferred / ${sourcing.constructed} constructed.`);
}
