#!/usr/bin/env node
/**
 * Builds the scenario/action divergence review worksheet for the Full Corpus
 * executable subset.
 *
 * The property under review is §6.3 of SOURCE_TO_POLICY_FIDELITY_REVIEW.md: does the
 * fixed fact pattern lie where the represented policies actually produce different
 * institutional actions? That is a judgment about the case, not a property of the file,
 * so this script does not decide it. It lays each family out in the one arrangement that
 * makes the judgment cheap: the decision question, the stipulations that fix the facts,
 * and every candidate's action side by side under it.
 *
 * Generated. Verdicts live in DIVERGENCE_REVIEW.md, which is written by hand.
 */
import { readFileSync, writeFileSync } from 'node:fs';

const MANIFEST = 'releases/full-corpus-v1-completion-candidate/manifest.json';
const OUT = 'docs/full-corpus/review/divergence-worksheet.md';

const manifest = JSON.parse(readFileSync(MANIFEST, 'utf8'));

// One worksheet entry per family; the concise record carries the same candidate field as
// the detailed one by companion equivalence, so read whichever is present.
const byFamily = new Map();
for (const r of manifest.records) {
  const family = r.record_id.slice(0, 4).toUpperCase();
  const prev = byFamily.get(family);
  if (!prev || r.representation === 'concise') byFamily.set(family, r);
}

const POOL_LABEL = { public: 'public', expert: 'expert', framework: 'framework' };

const lines = [];
lines.push('# Scenario/action divergence worksheet — Full Corpus executable subset');
lines.push('');
lines.push('**Generated by `scripts/divergence-worksheet.mjs`. Do not edit by hand.**');
lines.push('Verdicts are recorded in `DIVERGENCE_REVIEW.md`.');
lines.push('');
lines.push('For each family: the decision the scenario puts to the system, the stipulations that');
lines.push('fix the facts, and every candidate\'s action. The question to answer from this page is');
lines.push('whether the stipulated facts sit where these actions actually come apart — or whether');
lines.push('some pair would do the same thing under them.');
lines.push('');
lines.push(`Families: ${byFamily.size}. Records: ${manifest.records.length}.`);
lines.push('');

const families = [...byFamily.keys()].sort();
for (const family of families) {
  const meta = byFamily.get(family);
  const rec = JSON.parse(readFileSync(meta.path, 'utf8'));
  lines.push('---');
  lines.push('');
  lines.push(`## ${family} — ${rec.title}`);
  lines.push('');
  const shape = Object.entries(rec.candidate_pools)
    .map(([pool, arr]) => `${arr.length} ${POOL_LABEL[pool] ?? pool}`)
    .join(' × ');
  lines.push(`\`${meta.benchmark_profile}\` · ${shape} · aggregation \`${meta.required_aggregation}\``);
  lines.push('');
  lines.push(`**Decision question.** ${rec.decision_question}`);
  lines.push('');
  lines.push('**Fixed fact pattern.**');
  lines.push('');
  lines.push(String(rec.scenario).replace(/\s+/g, ' ').trim());
  lines.push('');
  if (Array.isArray(rec.stipulations) && rec.stipulations.length) {
    lines.push('**Stipulations, and why each is held constant.**');
    lines.push('');
    for (const s of rec.stipulations) {
      if (typeof s === 'string') { lines.push(`- ${s}`); continue; }
      const why = s.rationale ? ` _(held constant: ${s.rationale})_` : '';
      lines.push(`- **${s.kind ?? 'fact'}** — ${s.statement ?? s.text ?? JSON.stringify(s)}${why}`);
    }
    lines.push('');
  }
  lines.push('**Candidate actions.**');
  lines.push('');
  lines.push('| id | pool | basis | action |');
  lines.push('|---|---|---|---|');
  for (const [pool, arr] of Object.entries(rec.candidate_pools)) {
    for (const c of arr) {
      const text = String(c.text).replace(/\s+/g, ' ').replace(/\|/g, '\\|');
      lines.push(`| \`${c.id}\` | ${POOL_LABEL[pool] ?? pool} | ${c.policy_basis} | ${text} |`);
    }
  }
  lines.push('');
}

const rendered = `${lines.join('\n')}\n`;

if (process.argv.includes('--check')) {
  let committed = null;
  try { committed = readFileSync(OUT, 'utf8'); } catch { /* absent */ }
  if (committed !== rendered) {
    console.error(`✗ divergence worksheet is stale. Run: node scripts/divergence-worksheet.mjs`);
    console.error('  The corpus changed since the scenario/action divergence review was run.');
    console.error('  Regenerate, then re-read DIVERGENCE_REVIEW.md against the families that moved.');
    process.exit(1);
  }
  console.log(`✓ divergence worksheet current for ${byFamily.size} families.`);
} else {
  writeFileSync(OUT, rendered);
  console.log(`✓ divergence worksheet: ${byFamily.size} families → ${OUT}`);
}
