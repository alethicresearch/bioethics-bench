#!/usr/bin/env node
/**
 * Builds the inference-bridge review worksheet.
 *
 * The four-basis rule requires every `source-informed-policy-inference` candidate to state its
 * bridge: what the source measured, what the candidate asserts, and which part is Bench-authored.
 * An earlier pass established that all of them state one. This worksheet exists for the harder
 * question, which no check reaches: whether the stated bridge actually licenses the policy.
 *
 * That question is the action-target alignment rule applied one candidate at a time — willingness
 * to use is not a policy to establish, uptake under a default is not endorsement, discomfort with
 * an act is not endorsement of a rule against it. So the worksheet puts the three things that
 * decide it side by side: what the source is, what the candidate directs an institution to do, and
 * what the record says connects them.
 *
 * Generated. Verdicts live in BRIDGE_REVIEW.md, which is written by hand.
 */
import { readFileSync, writeFileSync } from 'node:fs';

const MANIFEST = 'releases/full-corpus-v1-completion-candidate/manifest.json';
const OUT = 'docs/full-corpus/review/bridge-worksheet.md';

const manifest = JSON.parse(readFileSync(MANIFEST, 'utf8'));
const byFamily = new Map();
for (const r of manifest.records) {
  const family = r.record_id.slice(0, 4).toUpperCase();
  const prev = byFamily.get(family);
  if (!prev || r.representation === 'concise') byFamily.set(family, r);
}

const lines = [];
let count = 0;
const body = [];

for (const family of [...byFamily.keys()].sort()) {
  const rec = JSON.parse(readFileSync(byFamily.get(family).path, 'utf8'));
  const entries = [];
  for (const pool of ['public', 'expert']) {
    for (const c of rec.candidate_pools?.[pool] ?? []) {
      if (c.policy_basis !== 'source-informed-policy-inference') continue;
      count += 1;
      entries.push({ pool, c });
    }
  }
  if (!entries.length) continue;
  body.push('---', '', `## ${family} — ${rec.title}`, '');
  body.push(`**Decision question.** ${rec.decision_question}`, '');
  for (const { pool, c } of entries) {
    body.push(`### \`${c.id}\` (${pool})`, '');
    body.push(`**Directs:** ${String(c.text).replace(/\s+/g, ' ')}`, '');
    body.push(`**Stated bridge:** ${String(c.provenance?.summary ?? '').replace(/\s+/g, ' ')}`, '');
    body.push('**Sources:**', '');
    for (const s of c.provenance?.sources ?? []) {
      body.push(`- ${String(s.citation).replace(/\s+/g, ' ')}`);
    }
    body.push('');
  }
}

lines.push('# Inference-bridge worksheet — source-informed candidates');
lines.push('');
lines.push('**Generated by `scripts/bridge-worksheet.mjs`. Do not edit by hand.**');
lines.push('Verdicts are recorded in `BRIDGE_REVIEW.md`.');
lines.push('');
lines.push(`${count} candidates carry \`source-informed-policy-inference\`. Each states a bridge from`);
lines.push('what its sources measured to what it directs an institution to do. An earlier pass');
lines.push('established that the bridge is *stated*. The question here is whether it *holds*:');
lines.push('');
lines.push('- Does the source measure a preference, an attitude, a behaviour, or a policy position?');
lines.push('- Does the candidate direct an institution to do something the source\'s subjects were');
lines.push('  never asked about?');
lines.push('- Is the Bench-authored part identified, and is it doing more work than the source can bear?');
lines.push('');
lines.push(...body);

writeFileSync(OUT, `${lines.join('\n')}\n`);
console.log(`✓ bridge worksheet: ${count} candidates → ${OUT}`);
