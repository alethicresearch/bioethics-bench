#!/usr/bin/env node
// Keeps each executable family's dossier in agreement with its committed record.
//
// The dossiers were written before the candidate audits ran, so several still
// carry the pre-audit estimate ("likely 2 public x 1 expert x 2 framework,
// subject to candidate audit") while the committed record embodies a different,
// audited geometry. Nothing detected that drift, because the executable
// decision lived in prose and the geometry lived in JSON.
//
// This writes the audited result back into the dossier as a delimited block
// derived entirely from the record, and fails when a dossier and its record
// disagree. It records what the record *is* — frame, geometry, cross-source
// pair count, required aggregation, and the policy basis of each candidate. It
// deliberately does not generate evidentiary narrative: the prose judgment
// above the block stays as written, as research history, and source-to-policy
// fidelity remains a matter for human review.

import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dossierRoot = join(root, 'docs', 'full-corpus');
const recordDir = join(root, 'data', 'benchmark');

const BEGIN = '<!-- BEGIN AUDITED-EXECUTABLE-DECISION — generated by scripts/dossier-decision-sync.mjs -->';
const END = '<!-- END AUDITED-EXECUTABLE-DECISION -->';
const POOLS = ['public', 'expert', 'framework'];
const write = process.argv.includes('--write');

function dossierPaths() {
  const map = new Map();
  for (const batch of readdirSync(dossierRoot).filter((d) => d.startsWith('batch-')).sort()) {
    for (const file of readdirSync(join(dossierRoot, batch)).filter((f) => /^M\d{3}-deep-case\.md$/.test(f))) {
      map.set(file.slice(0, 4), join(dossierRoot, batch, file));
    }
  }
  return map;
}

function recordsFor(family) {
  const prefix = family.toLowerCase();
  return readdirSync(recordDir)
    .filter((f) => f.startsWith(`${prefix}-`) && f.endsWith('.json'))
    .sort()
    .map((f) => ({ file: f, record: JSON.parse(readFileSync(join(recordDir, f), 'utf8')) }));
}

// Cross-source comparison is between pools only, so a candidate's partner count
// is the size of the two pools it is not in. Equal pool sizes are the only case
// where every candidate has the same number of partners, and therefore the only
// case where Sum does not rank partly by pool shape.
function geometryOf(record) {
  const pools = record.candidate_pools ?? {};
  const sizes = POOLS.map((p) => (pools[p] ?? []).length);
  const [a, b, c] = sizes;
  return { sizes, pairs: a * b + a * c + b * c, asymmetric: !(a === b && b === c) };
}

function decisionBlock(family, entries) {
  const { record } = entries[0];
  const { sizes, pairs, asymmetric } = geometryOf(record);
  const [a, b, c] = sizes;
  const aggregation = record.required_aggregation
    ?? (record.benchmark_profile ? `via profile \`${record.benchmark_profile}\`` : 'not declared');

  const bases = new Map();
  for (const pool of POOLS) {
    for (const candidate of record.candidate_pools[pool] ?? []) {
      const key = `${pool} / ${candidate.policy_basis}`;
      bases.set(key, (bases.get(key) ?? 0) + 1);
    }
  }

  const lines = [
    BEGIN,
    '',
    `**Canonical frame:** \`${record.frame_id}@${record.frame_version}\`  `,
    `**Geometry:** \`${a} public × ${b} expert × ${c} framework\`  `,
    `**Cross-source pairs:** ${pairs}  `,
    `**Required aggregation:** ${aggregation}${asymmetric ? ' — Mean is mandatory; partner counts differ across candidates.' : ' — partner counts are equal, so Sum would not be shape-biased here.'}  `,
    `**Records:** ${entries.map((e) => `\`${e.record.record_id}\``).join(', ')}`,
    '',
    'Policy basis of the audited candidate set:',
    '',
    '| Source pool / policy basis | Candidates |',
    '|---|---|',
    ...[...bases.entries()].map(([key, n]) => `| ${key} | ${n} |`),
    '',
    'This block is derived from the committed record, not from the prose above it.',
    'Where the two differ, the record is the audited result and the prose is the',
    'pre-audit estimate, kept as research history. Nothing here certifies',
    'source-to-policy fidelity, which remains subject to independent human review.',
    '',
    END,
  ];
  return lines.join('\n');
}

const dossiers = dossierPaths();
const problems = [];
let changed = 0;
let checked = 0;

for (const [family, path] of [...dossiers].sort()) {
  const entries = recordsFor(family);
  const text = readFileSync(path, 'utf8');
  const hasBlock = text.includes(BEGIN);

  if (entries.length === 0) {
    if (hasBlock) problems.push(`${family}: carries an audited-decision block but has no record`);
    continue;
  }

  // Companion records must agree on geometry, or the block would describe only one of them.
  const shapes = new Set(entries.map((e) => geometryOf(e.record).sizes.join('x')));
  if (shapes.size > 1) {
    problems.push(`${family}: companion records disagree on geometry (${[...shapes].join(' vs ')})`);
    continue;
  }

  checked += 1;
  const block = decisionBlock(family, entries);
  let updated;
  if (hasBlock) {
    const start = text.indexOf(BEGIN);
    const end = text.indexOf(END) + END.length;
    updated = text.slice(0, start) + block + text.slice(end);
  } else {
    updated = `${text.replace(/\s*$/, '')}\n\n## Audited executable decision\n\n${block}\n`;
  }

  if (updated !== text) {
    if (write) {
      writeFileSync(path, updated);
      changed += 1;
    } else {
      problems.push(`${family}: dossier disagrees with its record. Run: node scripts/dossier-decision-sync.mjs --write`);
    }
  }
}

if (problems.length) {
  for (const p of problems) console.error(`✗ ${p}`);
  process.exit(1);
}

console.log(
  write
    ? `✓ synced ${changed} dossier(s) to their records across ${checked} executable families.`
    : `✓ ${checked} executable dossiers agree with their committed records.`,
);
